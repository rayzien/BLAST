def prompt_input(prompt_text: str, default: str = "", is_secret: bool = False) -> str:
    """Prompt user for input with an optional default value."""
    if default:
        display_default = default if not is_secret else f"{default[:6]}...{default[-4:]}" if len(default) > 10 else "***"
        text = f"{prompt_text} [default: {display_default}]: "
    else:
        text = f"{prompt_text}: "

    try:
        val = input(text).strip()
        if not val and default:
            return default
        return val
    except (KeyboardInterrupt, EOFError):
        print("\n[BLAST] Aborted by user.")
        sys.exit(0)


def save_env_file(env_vars: dict, filepath: str = ".env"):
    """Save configuration to .env file."""
    try:
        lines = ["# Blast Configuration (Generated by Blast CLI)\n"]
        for k, v in env_vars.items():
            lines.append(f"{k}={v}\n")
        with open(filepath, "w", encoding="utf-8") as f:
            f.writelines(lines)
        print(f"[BLAST] Saved configuration to {filepath}")
    except Exception as e:
        print(f"[WARN] Failed to write {filepath}: {e}")


def run_interactive_setup():
    """Interactive prompt for Supabase credentials and system configuration."""
    print("=" * 72)
    print("  BLAST CLI - SECURITY & QUEUE GATEWAY FOR SUPABASE")
    print("  Architecture: App -> Blast -> Supabase")
    print("  Authors: rayzien and pheonix14")
    print("  Zero Emojis Mode: Active")
    print("=" * 72)
    print("\nPlease enter your Supabase and Blast settings:\n")

    # 1. Supabase Project URL
    sup_url = prompt_input("Enter Supabase Project URL", default=config.SUPABASE_URL)
    while not sup_url:
        print("[ERROR] Supabase Project URL cannot be empty.")
        sup_url = prompt_input("Enter Supabase Project URL", default="")

    # 2. Supabase Anon Key
    sup_anon = prompt_input("Enter Supabase Anon Key (Public)", default=config.SUPABASE_ANON_KEY, is_secret=True)

    # 3. Supabase Service Role Key
    sup_service = prompt_input("Enter Supabase Service Role Key (Optional)", default=config.SUPABASE_SERVICE_ROLE_KEY, is_secret=True)

    # 4. Blast API Key
    blast_key = prompt_input("Enter Blast API Key for your Client Apps", default="blast-secret-key-1")

    # 5. Port
    port_str = prompt_input("Enter Blast Server Port", default=str(config.PORT))
    try:
        port = int(port_str)
    except ValueError:
        port = 8080

    # 6. Redis URL (Optional, for Render multi-instance clustering)
    redis_url = prompt_input("Enter Redis URL for Multi-Instance Cluster (Optional, press Enter for local SQLite)", default=config.REDIS_URL)

    # 7. Ask to save to .env
    save_choice = prompt_input("Save credentials to .env file? (Y/n)", default="Y").lower()
    if save_choice in ("y", "yes", ""):
        save_env_file({
            "SUPABASE_URL": sup_url,
            "SUPABASE_ANON_KEY": sup_anon,
            "SUPABASE_SERVICE_ROLE_KEY": sup_service,
            "BLAST_API_KEYS": blast_key,
            "BLAST_PORT": str(port),
            "REDIS_URL": redis_url,
        })

    # Apply to runtime config
    config.SUPABASE_URL = sup_url.rstrip("/")
    config.SUPABASE_ANON_KEY = sup_anon
    config.SUPABASE_SERVICE_ROLE_KEY = sup_service
    config.API_KEYS = [blast_key]
    config.PORT = port
    config.REDIS_URL = redis_url

    print("\n[BLAST] Starting Blast Gateway Server...")
    start_server(config)


def start_server(cfg: BlastConfig):
    """Start queue, cluster, workers, and HTTP server."""
    # 1. Initialize queue engine
    if cfg.REDIS_URL:
        try:
            storage = RedisQueueStorage(cfg.REDIS_URL)
            logger.queue("Distributed Redis storage active for cluster.")
        except Exception as e:
            logger.warn("QUEUE", f"Failed connecting to Redis ({e}), falling back to SQLite.")
            storage = SQLiteQueueStorage(cfg.DB_PATH)
    else:
        storage = SQLiteQueueStorage(cfg.DB_PATH)
        logger.queue(f"Durable SQLite storage active ({cfg.DB_PATH}).")

    # 2. Supabase HTTP client
    supabase_client = SupabaseClient(cfg)

    # 3. Worker supervisor
    supervisor = WorkerSupervisor(cfg, storage=storage, supabase_client=supabase_client)
    supervisor.start()

    # 4. Cluster manager
    cluster_mgr = ClusterManager(cfg)
    cluster_mgr.start()

    # 5. Web application
    app = create_app(
        cfg=cfg,
        storage=storage,
        supabase_client=supabase_client,
        worker_supervisor=supervisor,
        cluster_manager=cluster_mgr,
    )

    print("=" * 72)
    print(f"  [STATUS] Blast is RUNNING on http://{cfg.HOST}:{cfg.PORT}")
    print(f"  [TARGET] Supabase Backend: {cfg.SUPABASE_URL}")
    print(f"  [STORAGE] {'Redis (Distributed)' if cfg.REDIS_URL else 'SQLite (Local)'}")
    print(f"  [WORKERS] {cfg.MAX_WORKERS} active background worker threads")
    print(f"  [CLUSTER] Node ID: {cfg.NODE_ID}")
    print("=" * 72)
    print("Press Ctrl+C to stop.\n")

    try:
        run_simple(
            hostname=cfg.HOST,
            port=cfg.PORT,
            application=app,
            use_reloader=False,
            threaded=True,
        )
    finally:
        supervisor.stop()
        cluster_mgr.stop()
        supabase_client.close()
        logger.info("MAIN", "Blast shutdown completed.")


def main():
    parser = argparse.ArgumentParser(description="Blast CLI: Security & Queue Gateway for Supabase")
    subparsers = parser.add_subparsers(dest="command")

    # 'cli' sub-command or default interactive
    cli_parser = subparsers.add_parser("cli", help="Start interactive credential prompt and run Blast")
    run_parser = subparsers.add_parser("run", help="Run directly with existing environment / flags")
    run_parser.add_argument("--host", default=config.HOST)
    run_parser.add_argument("--port", type=int, default=config.PORT)
    run_parser.add_argument("--supabase-url", default=config.SUPABASE_URL)
    run_parser.add_argument("--workers", type=int, default=config.MAX_WORKERS)

    args, unknown = parser.parse_known_args()

    if args.command == "run":
        if args.supabase_url:
            config.SUPABASE_URL = args.supabase_url
        config.HOST = args.host
        config.PORT = args.port
        config.MAX_WORKERS = args.workers
        start_server(config)
    else:
        # Default or 'cli' command triggers interactive setup
        run_interactive_setup()


if __name__ == "__main__":
    main()
